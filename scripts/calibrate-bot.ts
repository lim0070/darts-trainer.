// Finds the scatter (mm) for each bot level so its 80% stats land mid-band.
// Run with `npm run calibrate`; writes src/engine/bot/calibration.ts.
import { writeFileSync } from 'node:fs';
import { targetMpr, targetPpr } from '../src/engine/bot/level';
import { simulateBotCricket, simulateBotLeg } from '../src/engine/bot/sim';
import { mulberry32 } from '../src/engine/rng';

const LEGS = 400;
const GAMES = 200;

function ppr80(preset: 'soft' | 'steel', sigma: number): number {
  const rng = mulberry32(2024);
  let pts = 0;
  let rounds = 0;
  for (let i = 0; i < LEGS; i++) {
    const m = simulateBotLeg(preset, sigma, rng);
    pts += m.p80pts ?? 0;
    rounds += m.p80rounds ?? 0;
  }
  return pts / rounds;
}

function mpr80(sigma: number): number {
  const rng = mulberry32(2025);
  let marks = 0;
  let rounds = 0;
  for (let i = 0; i < GAMES; i++) {
    const st = simulateBotCricket(sigma, rng);
    marks += st.p80marks;
    rounds += st.p80rounds;
  }
  return marks / rounds;
}

/** Bisection on log(sigma); the stat falls as scatter grows. */
function solve(target: number, measure: (sigma: number) => number): number {
  let lo = Math.log(2);
  let hi = Math.log(250);
  for (let k = 0; k < 14; k++) {
    const mid = (lo + hi) / 2;
    if (measure(Math.exp(mid)) > target) lo = mid;
    else hi = mid;
  }
  return Math.round(Math.exp((lo + hi) / 2) * 100) / 100;
}

const levels = Array.from({ length: 18 }, (_, i) => i + 1);
const soft = levels.map((l) => solve(targetPpr(l), (s) => ppr80('soft', s)));
console.log('soft', soft.join(', '));
const steel = levels.map((l) => solve(targetPpr(l), (s) => ppr80('steel', s)));
console.log('steel', steel.join(', '));
const cricket = levels.map((l) => solve(targetMpr(l), (s) => mpr80(s)));
console.log('cricket', cricket.join(', '));

writeFileSync(
  'src/engine/bot/calibration.ts',
  `// Generated by scripts/calibrate-bot.ts. Scatter (mm) per rating level 1–18.
// 01 levels target the middle of each 80% PPR band; Cricket levels the 80% MPR band.
export const SIGMA_01_SOFT = [${soft.join(', ')}];
export const SIGMA_01_STEEL = [${steel.join(', ')}];
export const SIGMA_CRICKET = [${cricket.join(', ')}];
`,
);
console.log('written');
